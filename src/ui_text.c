#define UI_FONT_COUNT ((int)(sizeof(ui_font) / sizeof(ui_font[0])))

static const unsigned char *ui_font_lookup(char c)
{
    for (int i = 0; i < UI_FONT_COUNT; i++)
    {
        if (ui_font[i].ch == c)
        {
            return ui_font[i].rows;
        }
    }

    return ui_font[0].rows; /* fallback: space */
}

typedef struct
{
    unsigned int color;
    short x;
    short y;
    short z;
} TextVertex;

static void ui_text_rect(
    int x,
    int y,
    int width,
    int height,
    unsigned int color
)
{
    TextVertex *v;

    v = (TextVertex *)sceGuGetMemory(2 * sizeof(TextVertex));

    v[0].color = color;
    v[0].x = x;
    v[0].y = y;
    v[0].z = 0;

    v[1].color = color;
    v[1].x = x + width;
    v[1].y = y + height;
    v[1].z = 0;

    sceGuDrawArray(
        GU_SPRITES,
        GU_COLOR_8888 | GU_VERTEX_16BIT | GU_TRANSFORM_2D,
        2,
        NULL,
        v
    );
}

void ui_text_draw(
    int x,
    int y,
    const char *text,
    unsigned int color,
    int scale
)
{
    int cx;

    if (!text || scale < 1)
    {
        return;
    }

    cx = x;

    while (*text)
    {
        const unsigned char *glyph = ui_font_lookup(*text);

        for (int row = 0; row < 7; row++)
        {
            unsigned char bits = glyph[row];

            for (int col = 0; col < 5; col++)
            {
                if (bits & (1 << (4 - col)))
                {
                    ui_text_rect(
                        cx + col * scale,
                        y + row * scale,
                        scale,
                        scale,
                        color
                    );
                }
            }
        }

        cx += 6 * scale; /* 5px glyph + 1px advance */
        text++;
    }
}

int ui_text_width(const char *text, int scale)
{
    int len = 0;

    if (!text || scale < 1)
    {
        return 0;
    }

    while (text[len])
    {
        len++;
    }

    if (len == 0)
    {
        return 0;
    }

    return (len * 6 - 1) * scale;
}

int ui_text_height(int scale)
{
    if (scale < 1)
    {
        return 0;
    }

    return 7 * scale;
}